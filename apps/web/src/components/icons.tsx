export type IconName = keyof typeof icons;

export function Icon({ name, className = "size-4", ...props }: { name: IconName } & Omit<SVGProps<SVGSVGElement>, "ref">) {
  const Component = icons[name];
  return <Component aria-hidden="true" strokeWidth={1.8} className={className} {...props} />;
}
